import { expect, test } from 'bun:test';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { launchService, stopService } from '../../support/service-launch.adapter';

test.skipIf(Bun.env.OFFICE_VERIFY_WEB !== '1')('Programs browser workflow preserves scope across instructions, material and chats', async () => {
  const scratch = mkdtempSync(join(tmpdir(), 'air-programs-browser-'));
  const service = await launchService({ env: { OFFICE_DATA_ROOT: scratch, OFFICE_LEMONADE_MODE: 'external', OFFICE_DEMO_MODE: '1' } });
  const browser = await chromium.launch({ args: ['--disable-gpu'] });
  const page = await browser.newPage({ viewport: { width: 1215, height: 991 } });
  const api = async (path: string, body?: unknown) => {
    const response = await fetch(`${service.base}${path}`, { method: body === undefined ? 'GET' : 'POST', headers: { authorization: `Bearer ${service.token}`, 'content-type': 'application/json', origin: 'http://127.0.0.1:5173' }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    if (!response.ok) throw new Error(`${path}: ${response.status} ${await response.text()}`);
    return response.json();
  };
  try {
    await page.addInitScript((base) => { window.__AIR_SERVICE_BASE__ = base; localStorage.setItem('air-office:stage-state-v1', JSON.stringify({ version: 1, surfaces: [{ id: 'programs', kind: 'programs', title: 'Programs' }], activeId: 'programs' })); }, service.base);
    await page.goto('http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: 'Programs', exact: true }).click();
    await page.getByRole('tree', { name: 'Library files', exact: true }).waitFor();
    await page.getByRole('button', { name: 'New program', exact: true }).click();
    await page.getByLabel('Program name', { exact: true }).fill('Product development');
    await page.getByRole('button', { name: 'Create program', exact: true }).click();
    await page.getByRole('button', { name: 'New project', exact: true }).click();
    await page.getByLabel('Project name', { exact: true }).fill('Release planning');
    await page.getByRole('button', { name: 'Create project', exact: true }).click();
    await page.getByRole('heading', { name: 'Release planning', exact: true }).waitFor();
    await page.getByRole('tab', { name: 'Instructions', exact: true }).click();
    await page.getByRole('textbox', { name: 'Instructions', exact: true }).fill('Use evidence and keep decisions traceable.');
    await page.getByRole('button', { name: 'Save instructions', exact: true }).click();
    const { nodes } = await api('/api/v1/workspace/nodes');
    const project = nodes.find((node: { kind: string; name: string }) => node.kind === 'project' && node.name === 'Release planning');
    expect(nodes.find((node: { id: string }) => node.id === project.parentId)?.kind).toBe('program');
    expect(project.instruction).toContain('traceable');
    const programRow = page.locator('[role="treeitem"][title="Product development"]');
    await programRow.click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Edit instructions…', exact: true }).click();
    expect(await page.getByRole('textbox', { name: 'Name', exact: true }).inputValue()).toBe('Product development');
    await page.getByRole('button', { name: /Release planning.*items/ }).click();
    await programRow.click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Edit instructions…', exact: true }).click();
    expect(await page.getByRole('textbox', { name: 'Name', exact: true }).inputValue()).toBe('Product development');
    await programRow.click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Connect local folder…', exact: true }).click();
    expect(await page.getByRole('main', { name: 'Programs' }).getByRole('tab', { name: 'Files', exact: true }).getAttribute('aria-selected')).toBe('true');
    expect(await page.getByRole('dialog').count()).toBe(0);
    await page.getByRole('button', { name: /Release planning.*items/ }).click();
    await page.getByRole('main', { name: 'Programs' }).getByRole('tab', { name: 'Files', exact: true }).click();
    const files = join(scratch, 'reference-material'); mkdirSync(files); writeFileSync(join(files, 'release.txt'), 'Release risks and milestones for the quarter.');
    await page.getByRole('button', { name: 'Add folder', exact: true }).click();
    const picker = page.getByRole('dialog', { name: 'Add folder to Release planning', exact: true });
    await picker.getByRole('button', { name: 'Select this folder', exact: true }).waitFor();
    await picker.getByLabel('Folder path', { exact: true }).fill(files);
    const browsed = page.waitForResponse((response) => response.url().includes('/api/v1/storage-folders?') && response.url().includes('reference-material'));
    await picker.getByRole('button', { name: 'Open folder', exact: true }).click();
    await browsed;
    const linked = page.waitForResponse((response) => response.url().endsWith(`/api/v1/workspace/scopes/${project.id}/folders`) && response.request().method() === 'POST');
    await picker.getByRole('button', { name: 'Select this folder', exact: true }).click();
    const { node: mount } = await (await linked).json();
    expect(mount.parentId).toBe(project.id);
    await page.getByRole('status').filter({ hasText: /^Folder added/ }).waitFor();
    await page.evaluate(() => window.dispatchEvent(new Event('office-workspace-changed')));
    await page.getByRole('tab', { name: 'Indexing', exact: true }).click();
    await page.getByRole('button', { name: 'Refresh sources', exact: true }).click();
    await page.getByRole('status').filter({ hasText: /^1 sources refreshed/ }).waitFor();
    const assigned = page.waitForResponse((response) => response.url().includes('/api/v1/conversations/') && response.request().method() === 'PATCH');
    await page.getByRole('button', { name: 'Start chat', exact: true }).click();
    expect((await assigned).ok()).toBe(true);
    const { conversations } = await api('/api/v1/conversations');
    expect(conversations.some((chat: { folderId: string }) => chat.folderId === project.id)).toBe(true);
    await page.waitForFunction(() => !document.querySelector<HTMLButtonElement>('.programs-scope > header button')?.disabled);
    await page.getByRole('main', { name: 'Programs' }).getByRole('tab', { name: 'Files', exact: true }).click();
    const imageRoot = join(scratch, 'screenshots');
    mkdirSync(imageRoot, { recursive: true });
    await page.screenshot({ path: join(imageRoot, 'programs-light.png') });
    await page.locator('#stage-panel').evaluate((element) => { element.scrollTop = 0; });
    await page.screenshot({ path: join(imageRoot, 'programs-overview.png') });
    await page.evaluate(() => localStorage.setItem('air-office:theme', 'dark'));
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: /Release planning.*items/ }).click();
    await page.screenshot({ path: join(imageRoot, 'programs-dark.png') });
    await page.setViewportSize({ width: 640, height: 900 });
    expect(await page.locator('.programs-workspace').evaluate((element) => element.scrollWidth > element.clientWidth)).toBe(false);
    await page.screenshot({ path: join(imageRoot, 'programs-narrow.png') });
    for (let index = 0; index < 12; index += 1) {
      await api('/api/v1/workspace/nodes', { id: crypto.randomUUID(), kind: 'program', name: `Operations ${index + 1}` });
      await api('/api/v1/workspace/nodes', { id: crypto.randomUUID(), kind: 'project', parentId: project.parentId, name: `Quarterly delivery and stakeholder review ${index + 1}` });
    }
    await page.evaluate(() => window.dispatchEvent(new Event('office-workspace-changed')));
    await page.getByRole('button', { name: /Quarterly delivery and stakeholder review 12/ }).waitFor();
    expect(await page.locator('.programs-navigation').evaluate((element) => element.scrollHeight > element.clientHeight)).toBe(true);
    expect(await page.locator('.programs-project-grid').evaluate((element) => element.scrollHeight > element.clientHeight)).toBe(true);
    await page.screenshot({ path: join(imageRoot, 'programs-many.png') });
    await page.getByRole('searchbox', { name: 'Find a program' }).fill('Product development');
    await page.getByRole('textbox', { name: 'Find a project' }).fill('Release planning');
    expect(await page.locator('.programs-navigation button').count()).toBe(1);
    expect(await page.locator('.programs-project-grid button').count()).toBe(2);
  } finally { await browser.close(); await stopService(service.processHandle); rmSync(scratch, { recursive: true, force: true }); }
}, 90000);
