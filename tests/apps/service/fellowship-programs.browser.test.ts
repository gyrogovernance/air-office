import { expect, test } from 'bun:test';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import type { WorkspaceNode } from '@office/workspace/domain';
import { createRichDocument, markdownToNativeBody, exportRichDocument } from '@office/editor/rich-document-domain';
import { launchService, stopService } from '../../support/service-launch.adapter';

test.skipIf(Bun.env.OFFICE_VERIFY_WEB !== '1')('Fellowship and Craft keep creation, review sources and saved results in the same managed project', async () => {
  const scratch = mkdtempSync(join(tmpdir(), 'air-research-browser-'));
  const service = await launchService({ env: { OFFICE_DATA_ROOT: scratch, OFFICE_LEMONADE_MODE: 'external', OFFICE_DEMO_MODE: '1' } });
  const browser = await chromium.launch({ args: ['--disable-gpu'] });
  const page = await browser.newPage({ viewport: { width: 1215, height: 991 } });
  const api = async (path: string, body?: unknown) => {
    const response = await fetch(`${service.base}${path}`, { method: body === undefined ? 'GET' : 'POST', headers: { authorization: `Bearer ${service.token}`, 'content-type': 'application/json', origin: 'http://127.0.0.1:5173' }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    if (!response.ok) throw new Error(`${path}: ${response.status} ${await response.text()}`);
    return response.json();
  };
  const catalog = async (): Promise<WorkspaceNode[]> => (await api('/api/v1/workspace/nodes')).nodes;
  async function addNote(parentId: string, title: string, content: string) {
    const document = { ...createRichDocument(title, crypto.randomUUID()), body: markdownToNativeBody(content) };
    const { document: stored } = await api('/api/v1/rich-documents', document);
    await api('/api/v1/workspace/nodes', { id: crypto.randomUUID(), kind: 'note', parentId, name: title, targetId: stored.path ?? stored.id });
  }
  try {
    await page.addInitScript((base) => { window.__AIR_SERVICE_BASE__ = base; localStorage.setItem('air-office:stage-state-v1', JSON.stringify({ version: 1, surfaces: [{ id: 'fellowship', kind: 'fellowship', title: 'Fellowship' }], activeId: 'fellowship' })); }, service.base);
    await page.goto('http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
    const question = 'Can AI tutors explain corrections using inspectable evidence?';
    await page.getByRole('textbox', { name: 'Working question' }).fill(question);
    const prepared = page.waitForResponse((response) => response.url().includes('/workspace/scopes/') && response.url().endsWith('/knowledge') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Start project', exact: true }).click();
    await prepared;
    const project = (await catalog()).find((node) => node.kind === 'project' && node.name === question);
    if (!project || project.kind !== 'project') throw new Error('No research project was created.');
    expect((await catalog()).find((node) => node.id === project.parentId)?.name).toBe('AIR Fellowship');
    const files = join(scratch, 'evidence'); mkdirSync(files); writeFileSync(join(files, 'observations.txt'), 'TUTOR_FILE_EVIDENCE: corrections were checked against original examples.');
    await api(`/api/v1/workspace/scopes/${project.id}/folders`, { path: files });
    await addNote(project.parentId, 'Shared research practice', 'PROGRAM_SHARED_GUIDANCE: record uncertainty and original observations.');
    const { node: sibling } = await api('/api/v1/workspace/nodes', { id: crypto.randomUUID(), kind: 'project', parentId: project.parentId, name: 'Unrelated work' });
    await addNote(sibling.id, 'Sibling source', 'SIBLING_MUST_STAY_OUT_OF_REVIEW');
    await page.getByRole('button', { name: 'Go back', exact: true }).click();
    await page.getByRole('button', { name: 'Prepare for Craft', exact: true }).click();
    const submission = page.waitForResponse((response) => response.url().includes('/workspace/scopes/') && response.url().endsWith('/knowledge') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Prepare submission record', exact: true }).click();
    await submission;
    expect((await catalog()).filter((node) => node.kind === 'note' && node.name.startsWith('AIR-Craft submission record')).map((node) => node.parentId)).toEqual([project.id]);
    await page.getByRole('button', { name: 'Go back', exact: true }).click();
    await page.getByRole('button', { name: 'Prepare submission record', exact: true }).click();
    await page.getByRole('button', { name: 'Go back', exact: true }).waitFor();
    await page.waitForFunction(() => document.querySelector('[data-active-stage]')?.getAttribute('data-active-stage') !== 'craft');
    expect((await catalog()).filter((node) => node.kind === 'note' && node.name.startsWith('AIR-Craft submission record'))).toHaveLength(1);
    await page.getByRole('button', { name: 'Go back', exact: true }).click();
    await page.evaluate(() => sessionStorage.setItem('air-office:app-source-drafts', JSON.stringify({ 'policy-audit': { text: 'PERSONAL_APP_DRAFT', instructions: 'Personal constraints' } })));
    const imageRoot = join(scratch, 'screenshots');
    mkdirSync(imageRoot, { recursive: true });
    await page.locator('#stage-panel').evaluate((element) => { element.scrollTop = 0; });
    await page.screenshot({ path: join(imageRoot, 'craft-project-integration.png') });
    await page.emulateMedia({ colorScheme: 'dark' });
    await page.setViewportSize({ width: 640, height: 900 });
    expect(await page.locator('.craft-workspace').evaluate((element) => element.scrollWidth > element.clientWidth)).toBe(false);
    await page.screenshot({ path: join(imageRoot, 'craft-project-integration-dark-narrow.png') });
    await page.emulateMedia({ colorScheme: 'light' });
    await page.setViewportSize({ width: 1215, height: 991 });
    await page.getByRole('button', { name: 'Map claims and evidence', exact: false }).click();
    const source = page.getByRole('textbox', { name: 'Source material', exact: true });
    await source.waitFor();
    const reviewedText = await source.inputValue();
    expect(reviewedText).toContain(question);
    expect(reviewedText).toContain('TUTOR_FILE_EVIDENCE');
    expect(reviewedText).toContain('PROGRAM_SHARED_GUIDANCE');
    expect(reviewedText).not.toContain('SIBLING_MUST_STAY_OUT_OF_REVIEW');
    expect(await page.getByRole('textbox', { name: 'Optional scope' }).inputValue()).toContain('AIR Fellowship work');
    await page.screenshot({ path: join(imageRoot, 'review-project-integration.png') });
    await page.getByRole('combobox', { name: 'App model', exact: true }).click();
    await page.getByRole('option', { name: 'Demo model', exact: true }).click();
    await page.getByRole('button', { name: /^Run app/ }).click();
    await page.getByRole('status').filter({ hasText: 'Demo finished' }).waitFor();
    await source.fill('CHANGED_AFTER_THE_RUN');
    const saved = page.waitForResponse((response) => response.url().includes('/workspace/scopes/') && response.url().endsWith('/knowledge') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Save in project', exact: true }).click();
    await saved;
    const result = (await catalog()).find((node) => node.kind === 'note' && node.name.startsWith('Policy Auditing:'));
    if (!result || result.kind !== 'note') throw new Error('No review result was filed.');
    expect(result.parentId).toBe(project.id);
    const { documents } = await api('/api/v1/rich-documents');
    const record = documents.find((document: { id: string }) => document.id === result.targetId);
    const markdown = exportRichDocument(record, 'markdown').content;
    expect(markdown).toContain('Demo output. No AI review was performed.');
    expect(markdown).toContain('TUTOR_FILE_EVIDENCE');
    expect(markdown).not.toContain('CHANGED_AFTER_THE_RUN');
    await page.getByRole('button', { name: 'Go back', exact: true }).click();
    await page.getByRole('button', { name: 'Use without project', exact: true }).click();
    expect(await source.inputValue()).toBe('PERSONAL_APP_DRAFT');
    await page.getByRole('button', { name: 'Go back', exact: true }).click();
    await page.getByRole('button', { name: 'Open project', exact: true }).click();
    await page.getByRole('heading', { name: question, exact: true }).waitFor();
    await page.screenshot({ path: `${imageRoot}/research-project-integration.png` });
  } finally { await browser.close(); await stopService(service.processHandle); rmSync(scratch, { recursive: true, force: true }); }
}, 90000);
